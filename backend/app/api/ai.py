"""AI engine status and model listing."""

from __future__ import annotations

from fastapi import APIRouter, Depends

from app.api.deps import get_chat_service, get_config, get_providers
from app.core.chat_service import ChatService
from app.core.config import Settings
from app.core.errors import AppError
from app.providers.ollama import OLLAMA_INSTALL_HINT, model_is_installed
from app.providers.registry import ProviderRegistry
from app.schemas.ai import AIStatus, ModelInfo, ModelsResponse, OllamaStatus

router = APIRouter(prefix="/ai", tags=["ai"])


async def probe_ollama(providers: ProviderRegistry) -> tuple[OllamaStatus, list[ModelInfo]]:
    ollama = providers.ollama
    version = await ollama.version()
    if version is None:
        return OllamaStatus(available=False, base_url=ollama.base_url, error=OLLAMA_INSTALL_HINT), []
    try:
        models = await ollama.list_models()
    except AppError as exc:
        return OllamaStatus(available=False, base_url=ollama.base_url, version=version, error=exc.message), []
    return OllamaStatus(available=True, base_url=ollama.base_url, version=version, model_count=len(models)), models


@router.get("/status", response_model=AIStatus)
async def ai_status(
    providers: ProviderRegistry = Depends(get_providers),
    chat: ChatService = Depends(get_chat_service),
    config: Settings = Depends(get_config),
) -> AIStatus:
    settings = await chat.load_settings()
    ollama_status, models = await probe_ollama(providers)
    selected = settings.model
    installed = model_is_installed(selected, models)

    if settings.provider == "demo":
        state, message = "demo", "Demo Mode: replies are scripted and not generated by an AI model."
    elif not ollama_status.available:
        state, message = "offline", ollama_status.error or OLLAMA_INSTALL_HINT
    elif not models:
        state, message = "no_models", f"Ollama is running but no models are installed. Run `ollama pull {config.default_model}` to add one."
    elif not installed:
        state = "model_not_found"
        message = (
            f"The selected model '{selected}' is not installed. Choose one of the {len(models)} installed models."
            if selected
            else "No model selected. Choose an installed model to start chatting."
        )
    else:
        state, message = "ready", f"Local AI ready with {selected} via Ollama {ollama_status.version}."

    return AIStatus(
        provider=settings.provider,
        state=state,  # type: ignore[arg-type]
        selected_model=selected,
        model_available=installed,
        message=message,
        ollama=ollama_status,
        suggested_model=config.default_model,
    )


@router.get("/models", response_model=ModelsResponse)
async def list_models(
    providers: ProviderRegistry = Depends(get_providers),
    chat: ChatService = Depends(get_chat_service),
    config: Settings = Depends(get_config),
) -> ModelsResponse:
    settings = await chat.load_settings()
    ollama_status, models = await probe_ollama(providers)
    message = None
    if not ollama_status.available:
        message = ollama_status.error
    elif not models:
        message = f"No models installed yet. Run `ollama pull {config.default_model}` in a terminal; nothing is downloaded automatically."
    return ModelsResponse(
        provider=settings.provider,
        ollama_available=ollama_status.available,
        models=models,
        selected_model=settings.model,
        suggested_model=config.default_model,
        message=message,
    )
