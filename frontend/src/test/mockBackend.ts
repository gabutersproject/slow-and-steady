import type { AIStatus, AppSettings, ConversationSummary, Message, SettingsResponse } from '../types'

const defaultSettings: AppSettings = {
  provider: 'demo',
  model: null,
  temperature: 0.7,
  max_tokens: 1024,
  system_prompt: 'You are Slow and Steady.',
  stream: true,
}

export interface MockState {
  settings: AppSettings
  conversations: ConversationSummary[]
  messages: Record<string, Message[]>
  ollamaAvailable: boolean
  models: string[]
  delayMs: number
  streamChunks: string[]
}

export function createMockBackend(overrides: Partial<MockState> = {}) {
  const state: MockState = {
    settings: { ...defaultSettings },
    conversations: [],
    messages: {},
    ollamaAvailable: false,
    models: [],
    delayMs: 0,
    streamChunks: ['Hello ', 'from ', 'demo.'],
    ...overrides,
  }

  const json = (body: unknown, status = 200) =>
    new Response(JSON.stringify(body), { status, headers: { 'Content-Type': 'application/json' } })

  const error = (status: number, code: string, message: string) => json({ error: { code, message } }, status)

  const now = () => new Date().toISOString()
  const id = () => crypto.randomUUID().replaceAll('-', '')

  const aiStatus = (): AIStatus => {
    if (state.settings.provider === 'demo') {
      return {
        provider: 'demo',
        state: 'demo',
        selected_model: state.settings.model,
        model_available: false,
        message: 'Demo Mode: replies are scripted and not generated by an AI model.',
        ollama: {
          available: state.ollamaAvailable,
          base_url: 'http://127.0.0.1:11434',
          version: state.ollamaAvailable ? '0.5.0' : null,
          model_count: state.models.length,
          error: state.ollamaAvailable ? null : 'Ollama is not reachable.',
        },
        suggested_model: 'qwen2.5:1.5b',
      }
    }
    if (!state.ollamaAvailable) {
      return {
        provider: 'ollama',
        state: 'offline',
        selected_model: state.settings.model,
        model_available: false,
        message: 'Ollama is not reachable.',
        ollama: { available: false, base_url: 'http://127.0.0.1:11434', version: null, model_count: 0, error: 'Ollama is not reachable.' },
        suggested_model: 'qwen2.5:1.5b',
      }
    }
    const installed = Boolean(state.settings.model && state.models.includes(state.settings.model))
    return {
      provider: 'ollama',
      state: installed ? 'ready' : state.models.length === 0 ? 'no_models' : 'model_not_found',
      selected_model: state.settings.model,
      model_available: installed,
      message: installed ? `Local AI ready with ${state.settings.model}` : 'Model not available.',
      ollama: { available: true, base_url: 'http://127.0.0.1:11434', version: '0.5.0', model_count: state.models.length, error: null },
      suggested_model: 'qwen2.5:1.5b',
    }
  }

  const settingsResponse = (): SettingsResponse => ({
    settings: state.settings,
    limits: {
      temperature_min: 0,
      temperature_max: 2,
      max_tokens_min: 16,
      max_tokens_max: 8192,
      system_prompt_max_chars: 4000,
      message_max_chars: 8000,
    },
    default_system_prompt: 'You are Slow and Steady.',
  })

  const sse = (events: Array<{ event: string; data: unknown }>) => {
    const body = events.map((e) => `event: ${e.event}\ndata: ${JSON.stringify(e.data)}\n\n`).join('')
    return new Response(body, { status: 200, headers: { 'Content-Type': 'text/event-stream' } })
  }

  const handleChat = async (body: { conversation_id?: string | null; message: string; stream?: boolean }) => {
    if (!body.message?.trim()) return error(422, 'validation_error', 'Message cannot be blank.')
    let conversationId = body.conversation_id ?? null
    if (!conversationId) {
      conversationId = id()
      const created: ConversationSummary = {
        id: conversationId,
        title: body.message.slice(0, 40),
        created_at: now(),
        updated_at: now(),
        message_count: 0,
      }
      state.conversations.unshift(created)
      state.messages[conversationId] = []
    }
    const conversation = state.conversations.find((c) => c.id === conversationId)
    if (!conversation) return error(404, 'not_found', 'That conversation no longer exists.')
    const user: Message = {
      id: id(),
      conversation_id: conversationId,
      role: 'user',
      content: body.message,
      status: 'complete',
      provider: null,
      model: null,
      created_at: now(),
    }
    const assistant: Message = {
      id: id(),
      conversation_id: conversationId,
      role: 'assistant',
      content: state.streamChunks.join('') + '\n\n---\n*Demo Mode: this is a scripted reply, not output from a language model.*',
      status: 'complete',
      provider: 'demo',
      model: 'demo-scripted',
      created_at: now(),
    }
    state.messages[conversationId].push(user, assistant)
    conversation.message_count = state.messages[conversationId].length
    conversation.updated_at = now()

    const events = [
      { event: 'accepted', data: { conversation, user_message: user } },
      { event: 'start', data: { conversation_id: conversationId, assistant_message_id: assistant.id, provider: 'demo', model: 'demo-scripted' } },
      ...state.streamChunks.map((content) => ({ event: 'delta', data: { content } })),
      { event: 'done', data: { message: assistant, conversation, cancelled: false } },
    ]
    return sse(events)
  }

  const fetchImpl: typeof fetch = async (input, init) => {
    const url = typeof input === 'string' ? input : input instanceof URL ? input.href : input.url
    const method = (init?.method ?? 'GET').toUpperCase()
    const path = url.replace(/^https?:\/\/[^/]+/, '')
    const parsed = init?.body ? (JSON.parse(String(init.body)) as Record<string, unknown>) : {}

    if (path === '/api/health') return json({ status: 'ok', app: 'Slow and Steady', version: '0.1.0', database: 'ok' })
    if (path === '/api/settings' && method === 'GET') return json(settingsResponse())
    if (path === '/api/settings' && method === 'PUT') {
      state.settings = { ...state.settings, ...(parsed as Partial<AppSettings>) }
      return json(settingsResponse())
    }
    if (path === '/api/ai/status') return json(aiStatus())
    if (path === '/api/ai/models') {
      return json({
        provider: state.settings.provider,
        ollama_available: state.ollamaAvailable,
        models: state.models.map((name) => ({ name, size_bytes: null, parameter_size: null, quantization: null, family: null, modified_at: null })),
        selected_model: state.settings.model,
        suggested_model: 'qwen2.5:1.5b',
        message: state.ollamaAvailable ? null : 'Ollama is not reachable.',
      })
    }
    if (path === '/api/conversations' && method === 'GET') return json(state.conversations)
    if (path === '/api/conversations' && method === 'POST') {
      const created: ConversationSummary = { id: id(), title: (parsed.title as string) || 'New chat', created_at: now(), updated_at: now(), message_count: 0 }
      state.conversations.unshift(created)
      state.messages[created.id] = []
      return json(created, 201)
    }
    const one = path.match(/^\/api\/conversations\/([a-z0-9]+)$/)
    if (one && method === 'GET') {
      const conversation = state.conversations.find((c) => c.id === one[1])
      if (!conversation) return error(404, 'not_found', 'That conversation no longer exists.')
      return json({ ...conversation, messages: state.messages[one[1]] ?? [] })
    }
    if (one && method === 'PATCH') {
      const conversation = state.conversations.find((c) => c.id === one[1])
      if (!conversation) return error(404, 'not_found', 'That conversation no longer exists.')
      conversation.title = String(parsed.title)
      return json(conversation)
    }
    if (one && method === 'DELETE') {
      state.conversations = state.conversations.filter((c) => c.id !== one[1])
      delete state.messages[one[1]]
      return new Response(null, { status: 204 })
    }
    if (path.startsWith('/api/conversations') && method === 'DELETE') {
      const count = state.conversations.length
      state.conversations = []
      state.messages = {}
      return json({ deleted: count })
    }
    if (path === '/api/chat/stream' && method === 'POST') {
      return handleChat(parsed as { conversation_id?: string; message: string })
    }
    if (path === '/api/chat' && method === 'POST') {
      const streamed = await handleChat(parsed as { conversation_id?: string; message: string })
      return streamed
    }
    const regen = path.match(/^\/api\/chat\/([a-z0-9]+)\/regenerate$/)
    if (regen && method === 'POST') {
      const conversationId = regen[1]
      const history = state.messages[conversationId] ?? []
      while (history.length && history[history.length - 1].role === 'assistant') history.pop()
      const assistant: Message = {
        id: id(),
        conversation_id: conversationId,
        role: 'assistant',
        content: 'Regenerated reply.\n\n---\n*Demo Mode: this is a scripted reply, not output from a language model.*',
        status: 'complete',
        provider: 'demo',
        model: 'demo-scripted',
        created_at: now(),
      }
      history.push(assistant)
      const conversation = state.conversations.find((c) => c.id === conversationId)!
      conversation.message_count = history.length
      return sse([
        { event: 'accepted', data: { conversation, user_message: null } },
        { event: 'start', data: { conversation_id: conversationId, assistant_message_id: assistant.id, provider: 'demo', model: 'demo-scripted' } },
        { event: 'delta', data: { content: assistant.content } },
        { event: 'done', data: { message: assistant, conversation, cancelled: false } },
      ])
    }
    const cancel = path.match(/^\/api\/chat\/([a-z0-9]+)\/cancel$/)
    if (cancel && method === 'POST') return json({ conversation_id: cancel[1], cancelled: true })
    return error(404, 'not_found', `No mock for ${method} ${path}`)
  }

  return { state, fetchImpl }
}
